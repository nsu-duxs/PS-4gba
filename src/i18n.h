static inline const char* i18n_get(StringId id) {
    if ((unsigned int)id >= (unsigned int)STR_STRING_COUNT) {
        return "";
    }
    AppLanguage lang = g_current_language;
    if ((unsigned int)lang >= (unsigned int)LANG_COUNT) {
        lang = LANG_EN_US;
    }
    const char* s = g_strings[lang][id];
    return s ? s : "";
}

